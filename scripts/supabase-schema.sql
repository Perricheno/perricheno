-- RPC For Deducting Usage Safely

CREATE OR REPLACE FUNCTION deduct_user_usage(
    p_user_id BIGINT,
    p_free_deduction BIGINT,
    p_purchased_deduction BIGINT,
    p_amount BIGINT
) RETURNS void AS $$
BEGIN
    -- Update user balance: track ALL usage in daily/weekly/monthly, deduct purchased separately
    UPDATE users 
    SET 
        daily_chars_used = daily_chars_used + p_amount,
        weekly_chars_used = weekly_chars_used + p_amount,
        monthly_chars_used = COALESCE(monthly_chars_used, 0) + p_amount,
        purchased_chars = purchased_chars - p_purchased_deduction
    WHERE id = p_user_id;

    -- Record transaction if amount > 0
    IF p_amount > 0 THEN
        INSERT INTO transactions (user_id, topic, amount_text, is_positive)
        VALUES (p_user_id, 'Agent generation', '-' || p_amount || ' chars', false);

        INSERT INTO usage_logs (user_id, tokens)
        VALUES (p_user_id, p_amount);
    END IF;
END;
$$ LANGUAGE plpgsql;

